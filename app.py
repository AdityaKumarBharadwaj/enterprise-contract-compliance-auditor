"""
Enterprise Contract Compliance Auditor - Streamlit UI
Interactive web dashboard to test and demo the Bedrock auditor with Dynamic Multi-Query RAG.
"""

import os
import streamlit as st
from dotenv import load_dotenv
from audit_engine import audit_contract_with_kb, DEFAULT_MODEL_ID, MICRO_MODEL_ID, CLAUDE_MODEL_ID

load_dotenv()

st.set_page_config(
    page_title="Enterprise Contract Compliance Auditor | AWS Bedrock",
    page_icon="🛡️",
    layout="wide"
)

# Load local sample files if available
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
DATA_DIR = os.path.join(BASE_DIR, "data")

def load_file(filename):
    path = os.path.join(DATA_DIR, filename)
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as f:
            return f.read()
    return ""

policy_text = load_file("company_policy.txt")
non_compliant_sample = load_file("sample_contract_non_compliant.txt")
compliant_sample = load_file("sample_contract_compliant.txt")

# Sidebar - Configuration
with st.sidebar:
    st.image("https://upload.wikimedia.org/wikipedia/commons/9/93/Amazon_Web_Services_Logo.svg", width=80)
    st.title("Settings")
    st.markdown("### AWS Bedrock Config")
    
    kb_id = st.text_input(
        "Knowledge Base ID",
        value=os.environ.get("BEDROCK_KB_ID", ""),
        placeholder="e.g. YOUR_KB_ID",
        help="The 10-character ID of your Bedrock Knowledge Base."
    )
    
    aws_region = st.selectbox(
        "AWS Region",
        options=["us-east-1", "us-west-2", "eu-central-1", "ap-southeast-1"],
        index=0
    )
    
    model_choice = st.selectbox(
        "Audit Synthesis Model",
        options=[
            ("Amazon Nova Lite (Fast & High Intelligence)", DEFAULT_MODEL_ID),
            ("Amazon Nova Micro (Ultra-Fast & Economical)", MICRO_MODEL_ID),
            ("Anthropic Claude Haiku 4.5 (Marketplace)", CLAUDE_MODEL_ID)
        ],
        format_func=lambda x: x[0]
    )
    selected_model_id = model_choice[1]

    st.divider()
    st.markdown("### 📘 Architecture Highlights")
    st.info(
        "**Multi-Tier Dynamic Architecture:**\n"
        "- **Tier 1 Triage:** Amazon Nova Micro (Generates dynamic queries from contract)\n"
        "- **Tier 2 RAG:** Bedrock Knowledge Base (Multi-query search against OpenSearch Serverless)\n"
        "- **Tier 3 Synthesis:** Amazon Nova Lite / Claude (Clause-by-clause audit)\n"
        "- **Embeddings:** Titan Text Embeddings v2\n"
        "- **Observability:** De-duplicated grounding citations"
    )

# Main Screen Header
st.title("🛡️ Enterprise Contract Compliance Auditor")
st.caption("Powered by Amazon Bedrock Knowledge Bases & Dynamic Multi-Tier AI")

tab1, tab2 = st.tabs(["📝 Contract Audit & Execution", "📜 Active Company Policies"])

with tab1:
    col_input, col_preset = st.columns([3, 1])
    
    with col_preset:
        st.markdown("#### Load Test Sample:")
        if st.button("🔴 Load Non-Compliant Contract"):
            st.session_state["contract_text"] = non_compliant_sample
        if st.button("🟢 Load Compliant Contract"):
            st.session_state["contract_text"] = compliant_sample
        if st.button("Clear Input"):
            st.session_state["contract_text"] = ""

    with col_input:
        current_contract = st.session_state.get("contract_text", non_compliant_sample)
        contract_input = st.text_area(
            "Paste Vendor Contract to Audit:",
            value=current_contract,
            height=260,
            placeholder="Paste contract text here..."
        )

    audit_btn = st.button("🚀 Run Dynamic Compliance Audit", type="primary", use_container_width=True)

    if audit_btn:
        if not contract_input.strip():
            st.warning("Please paste or load a contract to audit.")
        elif not kb_id.strip():
            st.error("⚠️ Please enter your Bedrock Knowledge Base ID in the sidebar.")
        else:
            with st.spinner("🤖 Tier 1: Nova Micro analyzing contract & generating dynamic queries..."):
                result = audit_contract_with_kb(
                    contract_text=contract_input,
                    kb_id=kb_id,
                    model_id=selected_model_id,
                    region=aws_region
                )

                if result["success"]:
                    st.success("Audit Completed Successfully via Multi-Tier RAG!")
                    
                    # Display the Dynamic Queries generated by Nova Micro
                    if result.get("dynamic_queries"):
                        with st.expander("🎯 Tier 1: Dynamically Generated Search Queries (Nova Micro)", expanded=True):
                            st.caption("Amazon Nova Micro inspected the contract and dynamically formed these queries to eliminate blind spots:")
                            for q in result["dynamic_queries"]:
                                st.markdown(f"- 🔍 `{q}`")

                    # Display the Audit Report
                    st.markdown("### 📋 Audit Findings & Report")
                    st.markdown(result["report"])

                    # Display Citations
                    if result.get("citations"):
                        with st.expander(f"📚 Tier 2: Retrieved Grounding Citations ({len(result['citations'])} unique chunks)", expanded=False):
                            for idx, cit in enumerate(result["citations"]):
                                st.markdown(f"**Source {idx+1}:** `{cit['source']}` (Triggered by query: `{cit.get('matched_query', 'N/A')}` | Score: `{cit.get('score', 0):.3f}`)")
                                st.code(cit["text"], language="text")
                else:
                    st.error(result["error"])

with tab2:
    st.subheader("Current Golden Policy Guidelines (Ingested in Knowledge Base)")
    st.markdown("These are the corporate rules uploaded to your S3 bucket that the Knowledge Base indexes.")
    st.text_area("Policy Content (`data/company_policy.txt`)", value=policy_text, height=350, disabled=True)
